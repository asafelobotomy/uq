#!/usr/bin/env bash
# Tests for native/uq-loc/check-loc.sh: what counts as a line of code in each language, the limit,
# and the files it leaves out (generated, vendored, ignored, not source).
set -u
uq=$(cd "$(dirname "$0")/../.." && pwd)
loc=$uq/native/uq-loc/check-loc.sh
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
fails=0
ok() { if "$@" >/dev/null 2>&1; then echo "ok: $*"; else echo "FAIL: $*"; fails=$((fails + 1)); fi; }
no() { if "$@" >/dev/null 2>&1; then echo "FAIL (passed): $*"; fails=$((fails + 1)); else echo "ok (fails): $*"; fi; }
# count FILE: the number --top 1 reports for it
count() { "$loc" --top 1 "$1" 2>/dev/null | grep -E '^[0-9]+ ' | head -n 1 | cut -d' ' -f1; }
is() { local got; got=$(count "$1"); if [ "$got" = "$2" ]; then echo "ok: $1 has $2"; else echo "FAIL: $1 has $got, want $2"; fails=$((fails + 1)); fi; }

cd "$tmp" || exit 1
git init -q .
cat > a.rs <<'RS'
//! module docs
/// item docs
#[derive(Debug)]
struct A; // trailing comment still code

/* one-line block */
/*
 * a block
 */ let x = 1;
fn main() {}
RS
is a.rs 4

cat > a.py <<'PY'
#!/usr/bin/env python3
"""Module docstring
over two lines."""
import os  # code

def f():
    """One-line docstring."""
    s = """not a docstring:
    the string is code"""
    return s
PY
is a.py 5

cat > a.lua <<'LUA'
-- comment
--[[ block
still block ]]
local x = 1
LUA
is a.lua 1

printf '#!/bin/sh\n# comment\necho hi\n\n' > tool
is tool 1
printf 'plain text\n' > NOTES
ok "$loc" NOTES
ok test -z "$(count NOTES)"

for i in $(seq 1 401); do echo "let v$i = $i;"; done > big.js
is big.js 401
no "$loc" big.js
ok env LOC_MAX=401 "$loc" big.js
head -n 400 big.js > edge.js
ok "$loc" edge.js

{ echo "// @generated by a tool"; cat big.js; } > gen.js
ok test -z "$(count gen.js)"
mkdir -p vendor/x fixtures src uq
cp big.js vendor/x/lib.js; cp big.js fixtures/data.js; cp big.js src/kit.js; cp big.js src/data.js
printf '[uq-theme]\nversion = "1.0.0"\nfiles = ["src/kit.js"]\n' > uq/native.toml
printf '# tables generated at build time\nsrc/data.js\n' > uq/loc-ignore
ok "$loc" vendor/x/lib.js fixtures/data.js src/kit.js src/data.js gen.js
git add -A
no "$loc"
git rm -q --cached big.js
ok "$loc"

if [ $fails = 0 ]; then echo "all passed"; else echo "$fails failed"; exit 1; fi
