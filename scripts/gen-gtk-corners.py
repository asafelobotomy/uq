#!/usr/bin/env python3
"""Generate the corner rules at the end of templates/gtk3.css.j2 and templates/gtk4.css.j2.

GTK has no corner-radius setting, and libadwaita exposes only `--window-radius`, so the theme's
radius reaches GTK apps through the user's gtk.css (which imports uqd's rendered one). Rules
there have USER priority: they beat the toolkit's whatever their specificity, so overriding only
`button { border-radius }` would also round the inner corners of linked button groups, which the
toolkit squares with more specific rules. Instead this copies EVERY rule that sets a corner from
the toolkit's own stylesheet, in its order, keeping only the radius declarations, so the cascade
between them is the toolkit's, and swaps the toolkit's radii for the theme's:

    15px, 12px (windows, popovers, cards, boxed lists)  -> r, the theme's radius
    9px (buttons, entries, rows), 9.5px, 8px, 7px       -> c = r - 2 (and c + 0.5, c - 1, c - 2)
    6px and smaller                                     -> min(that, c)
    anything else (0, pills, circles, scrollbars)       -> unchanged

Sources (run on Arch with the packages uQ depends on installed):
    GTK 4: libadwaita's /org/gnome/Adwaita/styles/gtk.css (gresource in libadwaita-1.so.0)
    GTK 3: adw-gtk3-dark's gtk-3.0/gtk.css (adw-gtk-theme)

    scripts/gen-gtk-corners.py [--libadwaita FILE.css] [--adw-gtk3 FILE.css] [--check]

Without the source arguments it extracts them from the installed packages. --check exits 1 when
the templates differ from what would be written (it needs the same package versions).
"""
import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "/* corners: generated by scripts/gen-gtk-corners.py from {src}; do not edit by hand */"
END = "/* end of corners */"

PX = re.compile(r"(?<![\w.-])(\d+(?:\.\d+)?)px\b")


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def blocks(css: str):
    """Top-level items as (prelude, body); body is a str (declarations) or a list (nested)."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        inner = css[j + 1 : k - 1]
        if prelude.startswith("@"):
            out.append((prelude, blocks(inner) if "{" in inner else inner))
        else:
            out.append((prelude, inner))
        i = k
    return out


def map_px(m: re.Match) -> str:
    v = float(m.group(1))
    if v in (15, 12):
        return "{{ r }}px"
    if v == 9:
        return "{{ c }}px"
    if v == 9.5:
        return "{{ c }}.5px"
    if v == 8:
        return "{{ [c - 1, 0]|max }}px"
    if v == 7:
        return "{{ [c - 2, 0]|max }}px"
    if v <= 6 and v == int(v) and v > 0:
        return "{{ [%d, c]|min }}px" % v
    return m.group(0)


def radius_decls(body: str):
    out = []
    for d in body.split(";"):
        if ":" not in d:
            continue
        prop, val = d.split(":", 1)
        prop = prop.strip()
        if "radius" in prop:
            out.append(f"{prop}: {PX.sub(map_px, val.strip())}")
    return out


def emit(items, indent=""):
    lines = []
    for prelude, body in items:
        if isinstance(body, list):
            inner = emit(body, indent + "  ")
            if inner:
                lines.append(f"{indent}{prelude} {{")
                lines.extend(inner)
                lines.append(f"{indent}}}")
            continue
        if prelude.startswith("@"):
            continue
        decls = radius_decls(body)
        # :root's --window-radius is libadwaita's own variable for window corners.
        if prelude == ":root":
            decls = [d for d in decls if d.startswith("--window-radius")]
        if not decls:
            continue
        sel = " ".join(prelude.split())
        lines.append(f"{indent}{sel} {{ {'; '.join(decls)}; }}")
    return lines


def corners(css: str, src: str) -> str:
    head = (
        BEGIN.format(src=src)
        + "\n{%- set r = theme.ui.radius %}\n{%- set c = [r - 2, 0]|max %}\n"
    )
    return head + "\n".join(emit(blocks(strip_comments(css)))) + "\n" + END + "\n"


def splice(template: pathlib.Path, block: str) -> str:
    text = template.read_text()
    start = text.find("/* corners: generated")
    if start >= 0:
        end = text.index(END, start) + len(END) + 1
        text = text[:start] + text[end:]
    if not text.endswith("\n"):
        text += "\n"
    return text + block


def installed_sources():
    adw = subprocess.run(
        ["gresource", "extract", "/usr/lib/libadwaita-1.so.0", "/org/gnome/Adwaita/styles/gtk.css"],
        check=True, capture_output=True, text=True,
    ).stdout
    gtk3 = pathlib.Path("/usr/share/themes/adw-gtk3-dark/gtk-3.0/gtk.css").read_text()
    ver = lambda p: subprocess.run(["pacman", "-Q", p], capture_output=True, text=True).stdout.strip() or p
    return adw, ver("libadwaita"), gtk3, ver("adw-gtk-theme")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--libadwaita")
    ap.add_argument("--adw-gtk3")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.libadwaita and a.adw_gtk3:
        adw, adw_src = pathlib.Path(a.libadwaita).read_text(), "libadwaita"
        gtk3, gtk3_src = pathlib.Path(a.adw_gtk3).read_text(), "adw-gtk3"
    else:
        adw, adw_src, gtk3, gtk3_src = installed_sources()
    bad = 0
    for name, css, src in (("gtk4.css.j2", adw, adw_src), ("gtk3.css.j2", gtk3, gtk3_src)):
        path = ROOT / "templates" / name
        new = splice(path, corners(css, src))
        if a.check:
            if new != path.read_text():
                print(f"{path} is out of date: run scripts/gen-gtk-corners.py", file=sys.stderr)
                bad = 1
        else:
            path.write_text(new)
            print(f"wrote {path}")
    sys.exit(bad)


if __name__ == "__main__":
    main()
