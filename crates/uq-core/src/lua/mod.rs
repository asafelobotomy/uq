pub const HEADER: &str = "-- Generated by uqd. Edit user.lua instead.";

/// Layouts uQ offers per workspace (Hyprland also has `monocle`; not offered in Phase 1).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Layout {
    Dwindle,
    Master,
    Scrolling,
}

impl Layout {
    pub fn as_str(self) -> &'static str {
        match self {
            Layout::Dwindle => "dwindle",
            Layout::Master => "master",
            Layout::Scrolling => "scrolling",
        }
    }
}

#[derive(Debug, thiserror::Error)]
#[error("unknown layout {0:?} (expected dwindle, master or scrolling)")]
pub struct BadLayout(pub String);

impl FromStr for Layout {
    type Err = BadLayout;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "dwindle" => Ok(Layout::Dwindle),
            "master" => Ok(Layout::Master),
            "scrolling" => Ok(Layout::Scrolling),
            other => Err(BadLayout(other.to_string())),
        }
    }
}

/// The Hyprland workspace selector for a user-facing workspace name. Hyprland only matches a
/// name through `name:<n>` (a bare `web` parses as selector syntax and never matches), so plain
/// names get the prefix; ids, `name:`/`special` selectors and bracket selectors pass through.
pub fn workspace_selector(ws: &str) -> String {
    let ws = ws.trim();
    let passthrough = ws.parse::<i64>().is_ok()
        || ws.starts_with("name:")
        || ws.starts_with("special")
        || ws.contains('[');
    if passthrough {
        ws.to_string()
    } else {
        format!("name:{ws}")
    }
}

/// A double-quoted Lua string literal. Control bytes use 3-digit `\ddd` so a following digit
/// can't be absorbed into the escape.
pub fn lua_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                let _ = write!(out, "\\{:03}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

pub fn emit_workspace_rule(ws: &str, layout: Layout) -> String {
    rules::workspace_call(ws, Some(layout), None)
}

pub fn emit_generated(
    theme: &Theme,
    layouts: &BTreeMap<String, Layout>,
    rules: &Rules,
    settings: &Settings,
    startup: &StartupRender,
) -> String {
    emit_generated_with_apps(theme, layouts, rules, &[], settings, startup)
}

/// [`emit_generated`] with window rules from apps (Phase 4 §3.3), rendered after the workspace
/// rules and before the person's own window rules, so a rule of their own wins a conflict.
pub fn emit_generated_with_apps(
    theme: &Theme,
    layouts: &BTreeMap<String, Layout>,
    rules: &Rules,
    app_rules: &[crate::rules::WindowRule],
    settings: &Settings,
    startup: &StartupRender,
) -> String {
    let (c, ui) = (&theme.colors, &theme.ui);
    // Reduce motion (`ui.reduce_motion`) turns Hyprland's animations off, whatever `look` says.
    let reduced;
    let look = if settings.ui.reduce_motion {
        reduced = Look {
            animations: Some(false),
            ..settings.look.clone()
        };
        &reduced
    } else {
        &settings.look
    };
    let lo = &settings.layout_options;
    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}");
    let _ = writeln!(
        out,
        "-- Theme: {} ({})",
        // A Lua comment ends at \n or \r; no control character may reach the file.
        theme.name.replace(|c: char| c.is_control(), " "),
        theme.variant
    );
    let _ = writeln!(out, "hl.config({{");
    let _ = writeln!(out, "    general = {{");
    let _ = writeln!(
        out,
        "        gaps_in = {},",
        look.gaps_in.unwrap_or(ui.gap_in)
    );
    let _ = writeln!(
        out,
        "        gaps_out = {},",
        look.gaps_out.unwrap_or(ui.gap_out)
    );
    let _ = writeln!(
        out,
        "        border_size = {},",
        look.border_width.unwrap_or(ui.border_width)
    );
    if let Some(l) = lo.default {
        let _ = writeln!(out, "        layout = {},", lua_string(l.as_str()));
    }
    let _ = writeln!(out, "        col = {{");
    let _ = writeln!(
        out,
        "            active_border = {},",
        lua_string(&c.accent.rgba(0xff))
    );
    let _ = writeln!(
        out,
        "            inactive_border = {},",
        lua_string(&c.border.rgba(0xaa))
    );
    let _ = writeln!(out, "        }},");
    let _ = writeln!(out, "    }},");
    let _ = writeln!(out, "    decoration = {{");
    let _ = writeln!(
        out,
        "        rounding = {},",
        look.rounding.unwrap_or(ui.radius)
    );
    look::emit_decoration_extras(&mut out, look);
    let _ = writeln!(out, "    }},");
    look::emit_option_tables(&mut out, look, lo);
    input::emit_input(&mut out, &settings.mouse, &settings.input);
    emit_xwayland(&mut out, startup);
    let _ = writeln!(out, "}})");
    let monitors = emit_monitors(&settings.monitors);
    if !monitors.is_empty() {
        let _ = write!(out, "\n-- Monitors\n{monitors}");
    }
    let devices = emit_devices(&settings.input);
    if !devices.is_empty() {
        let _ = write!(out, "\n-- Input devices\n{devices}");
    }
    look::emit_animations(&mut out, look);
    // After base.lua's fixed size, so these win.
    let _ = writeln!(
        out,
        "hl.env(\"XCURSOR_THEME\", {})",
        lua_string(&theme.icons.cursor_theme)
    );
    let _ = writeln!(
        out,
        "hl.env(\"XCURSOR_SIZE\", {})",
        lua_string(&theme.icons.cursor_size.to_string())
    );
    let _ = writeln!(
        out,
        "hl.env(\"HYPRCURSOR_SIZE\", {})",
        lua_string(&theme.icons.cursor_size.to_string())
    );
    emit_startup_env(&mut out, startup);
    out.push_str(&emit_workspace_rules(layouts, &rules.workspace));
    out.push_str(&rules::emit_app_block(app_rules));
    out.push_str(&rules::emit_window_block(&rules.window));
    out.push_str(&rules::emit_layer_block(&rules.layer));
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::settings::{AccelProfile, MouseSettings};
    use crate::theme::{Theme, Variant, tests::FIXTURE};
    use std::collections::BTreeMap;

    fn theme() -> Theme {
        Theme::from_toml(FIXTURE, "fixture", Variant::Dark).unwrap()
    }

    #[test]
    fn generated_has_do_not_edit_header() {
        let out = emit_generated(
            &theme(),
            &BTreeMap::new(),
            &Rules::default(),
            &Settings::default(),
            &StartupRender::default(),
        );
        assert_eq!(
            out.lines().next(),
            Some("-- Generated by uqd. Edit user.lua instead.")
        );
    }

    #[test]
    fn theme_comment_has_no_control_characters() {
        let mut t = theme();
        t.name = "evil\r\nhl.exec(\"x\")\u{b}\u{1b}[2J\u{85}end".into();
        let out = emit_generated(
            &t,
            &BTreeMap::new(),
            &Rules::default(),
            &Settings::default(),
            &StartupRender::default(),
        );
        let line = out.lines().nth(1).unwrap();
        assert!(line.starts_with("-- Theme: evil"), "{line}");
        assert!(line.ends_with("end (dark)"), "{line}");
        assert!(!line.chars().any(char::is_control), "{line:?}");
        assert!(!out.contains('\r'));
    }

    #[test]
    fn emits_border_colours_gaps_and_rounding() {
        let out = emit_generated(
            &theme(),
            &BTreeMap::new(),
            &Rules::default(),
            &Settings::default(),
            &StartupRender::default(),
        );
        // fixture accent #d79921, border #665c54
        assert!(out.contains(r#"active_border = "rgba(d79921ff)""#), "{out}");
        assert!(
            out.contains(r#"inactive_border = "rgba(665c54aa)""#),
            "{out}"
        );
        assert!(out.contains("gaps_in = 5"), "{out}");
        assert!(out.contains("gaps_out = 12"), "{out}");
        assert!(out.contains("border_size = 2"), "{out}");
        assert!(out.contains("rounding = 10"), "{out}");
    }

    #[test]
    fn generated_sets_cursor_env() {
        let out = emit_generated(
            &theme(),
            &BTreeMap::new(),
            &Rules::default(),
            &Settings::default(),
            &StartupRender::default(),
        );
        assert!(
            out.contains(r#"hl.env("XCURSOR_THEME", "Bibata-Modern-Classic")"#),
            "{out}"
        );
        assert!(out.contains(r#"hl.env("XCURSOR_SIZE", "24")"#), "{out}");
        assert!(out.contains(r#"hl.env("HYPRCURSOR_SIZE", "24")"#), "{out}");
        let a = crate::settings::Appearance {
            cursor_theme: Some("Breeze_Snow".into()),
            cursor_size: Some(40),
            ..Default::default()
        };
        let out = emit_generated(
            &theme().with_appearance(&a),
            &BTreeMap::new(),
            &Rules::default(),
            &Settings::default(),
            &StartupRender::default(),
        );
        assert!(
            out.contains(r#"hl.env("XCURSOR_THEME", "Breeze_Snow")"#),
            "{out}"
        );
        assert!(out.contains(r#"hl.env("XCURSOR_SIZE", "40")"#), "{out}");
        assert!(out.contains(r#"hl.env("HYPRCURSOR_SIZE", "40")"#), "{out}");
    }

    #[test]
    fn emits_rules_sorted() {
        let layouts = BTreeMap::from([
            ("2".to_string(), Layout::Scrolling),
            ("1".to_string(), Layout::Master),
        ]);
        let out = emit_generated(
            &theme(),
            &layouts,
            &Rules::default(),
            &Settings::default(),
            &StartupRender::default(),
        );
        let one = out
            .find(r#"hl.workspace_rule({ workspace = "1", layout = "master" })"#)
            .expect("rule 1");
        let two = out
            .find(r#"hl.workspace_rule({ workspace = "2", layout = "scrolling" })"#)
            .expect("rule 2");
        assert!(one < two);
    }

    #[test]
    fn emits_default_mouse_input() {
        let out = emit_generated(
            &theme(),
            &BTreeMap::new(),
            &Rules::default(),
            &Settings::default(),
            &StartupRender::default(),
        );
        for want in [
            "    input = {",
            "sensitivity = 0.0,",
            "natural_scroll = false,",
            "left_handed = false,",
            "scroll_factor = 1.0,",
        ] {
            assert!(out.contains(want), "{want}\n{out}");
        }
        assert!(!out.contains("accel_profile"), "{out}");
    }

    #[test]
    fn emits_custom_mouse_input() {
        let m = MouseSettings {
            sensitivity: -0.35,
            accel_profile: AccelProfile::Flat,
            natural_scroll: true,
            left_handed: true,
            scroll_factor: 2.0,
        };
        let out = emit_generated(
            &theme(),
            &BTreeMap::new(),
            &Rules::default(),
            &Settings {
                mouse: m,
                ..Settings::default()
            },
            &StartupRender::default(),
        );
        for want in [
            "sensitivity = -0.35,",
            r#"accel_profile = "flat","#,
            "natural_scroll = true,",
            "left_handed = true,",
            "scroll_factor = 2.0,",
        ] {
            assert!(out.contains(want), "{want}\n{out}");
        }
        let m = MouseSettings {
            accel_profile: AccelProfile::Adaptive,
            ..MouseSettings::default()
        };
        let out = emit_generated(
            &theme(),
            &BTreeMap::new(),
            &Rules::default(),
            &Settings {
                mouse: m,
                ..Settings::default()
            },
            &StartupRender::default(),
        );
        assert!(out.contains(r#"accel_profile = "adaptive","#), "{out}");
    }

    #[test]
    fn workspace_selector_is_escaped() {
        assert_eq!(
            emit_workspace_rule("web\"x\\y", Layout::Dwindle),
            r#"hl.workspace_rule({ workspace = "web\"x\\y", layout = "dwindle" })"#
        );
    }

    #[test]
    fn workspace_selector_normalisation() {
        for (input, want) in [
            ("2", "2"),
            (" 3 ", "3"),
            ("web", "name:web"),
            ("name:web", "name:web"),
            ("special:magic", "special:magic"),
            ("special", "special"),
            ("w[tv1]", "w[tv1]"),
        ] {
            assert_eq!(workspace_selector(input), want, "{input:?}");
        }
    }

    #[test]
    fn lua_string_escapes_control_bytes() {
        assert_eq!(lua_string("a\nb\r\0\x071"), r#""a\nb\r\000\0071""#);
        assert_eq!(lua_string("special:magic"), r#""special:magic""#);
    }

    #[test]
    fn layout_parsing() {
        assert_eq!("scrolling".parse::<Layout>().unwrap(), Layout::Scrolling);
        assert_eq!(Layout::Master.as_str(), "master");
        assert!("monocle".parse::<Layout>().is_err());
        assert!("Dwindle".parse::<Layout>().is_err());
    }
}
